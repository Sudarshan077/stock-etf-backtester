"""Report writers: trades.csv, equity_curve.csv and a self-contained report.html.

The HTML report embeds everything inline -- styles, an SVG equity-curve
chart and the full trade table -- with NO external CSS, JS, images or
web fonts, so it renders identically offline on any browser.

Files are written to `<output_dir>/` (default ./output), created on demand.
"""

