# CSV writers
# ---------------------------------------------------------------------------

TRADE_COLUMNS = ["entry_date", "entry_price", "shares", "exit_date",
                 "exit_price", "pnl", "return_pct", "bars_held",
                 "exit_reason"]


def write_trades_csv(result, path):
    """Write the full trade log as CSV (one row per round trip)."""
    import csv
    with open(path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(TRADE_COLUMNS)
        for t in result.trades:
            w.writerow([t.entry_date, "%.2f" % t.entry_price, t.shares,
                         t.exit_date, "%.2f" % t.exit_price,
                         "%.2f" % t.pnl, "%.2f" % t.return_pct,
                         t.bars_held, t.exit_reason])


def write_equity_csv(result, path):
    """Write the per-bar equity curve as CSV."""
    import csv
    with open(path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["Date", "Equity"])
        for date, equity in result.equity_curve:
            w.writerow([date, "%.2f" % equity])


