def _equity_svg(result, width=860, height=300):
    """Render the equity curve as an inline SVG polyline chart.

    Scales to min/max equity with a small margin; dates label the
    start/middle/end.  No external libraries, no JS.
    """
    points = result.equity_curve
    if not points:
        return "<p>No equity points.</p>"
    values = [v for _, v in points]
    vmin, vmax = min(values), max(values)
    if vmax == vmin:
        vmax = vmin + 1.0
    pad_l, pad_r, pad_t, pad_b = 60, 15, 15, 30
    plot_w = width - pad_l - pad_r
    plot_h = height - pad_t - pad_b
    n = len(points)

    def x(i):
        return pad_l + (plot_w * i / (n - 1 if n > 1 else 1))

    def y(v):
        return pad_t + plot_h * (1 - (v - vmin) / (vmax - vmin))

    coords = " ".join("%.1f,%.1f" % (x(i), y(v)) for i, (_, v)
                      in enumerate(points))

    # 4 horizontal gridlines with value labels.
    grid = []
    for g in range(5):
        gv = vmin + (vmax - vmin) * g / 4.0
        gy = y(gv)
        grid.append('<line x1="%d" y1="%.1f" x2="%d" y2="%.1f" '
                    'stroke="#ddd" stroke-width="1"/>'
                    % (pad_l, gy, width - pad_r, gy))
        grid.append('<text x="%d" y="%.1f" font-size="10" fill="#666" '
                    'text-anchor="end">%.0f</text>'
                    % (pad_l - 6, gy + 3, gv))

    # Start / mid / end date labels.
    labels = []
    for idx, anchor in ((0, "start"), (n // 2, "middle"), (n - 1, "end")):
        labels.append('<text x="%.1f" y="%d" font-size="10" fill="#666" '
                      'text-anchor="%s">%s</text>'
                      % (x(idx), height - 8, anchor, points[idx][0]))

    return ('<svg xmlns="http://www.w3.org/2000/svg" width="%d" '
            'height="%d" viewBox="0 0 %d %d">'
            '<rect width="%d" height="%d" fill="#fff"/>'
            '%s'
            '<polyline points="%s" fill="none" stroke="#2563eb" '
            'stroke-width="1.5"/>'
            '%s'
            '</svg>') % (width, height, width, height, width, height,
                         "".join(grid), coords, "".join(labels))


def write_html_report(result, metrics, path, data_file=""):
    """Write the fully self-contained HTML report to `path`."""
    rows = []
    # label, format-string (uses {v} placeholder, rendered via format())
    nice = [
        ("initial_capital", "Initial capital", "${v:,.2f}"),
        ("final_equity", "Final equity", "${v:,.2f}"),
        ("total_return_pct", "Total return", "{v:.2f}%"),
        ("cagr_pct", "CAGR", "{v:.2f}%"),
        ("max_drawdown_pct", "Max drawdown", "{v:.2f}%"),
        ("max_drawdown_abs", "Max drawdown (dollars)", "${v:,.2f}"),
        ("longest_drawdown_bars", "Longest drawdown (bars)", "{v:d}"),
        ("sharpe", "Sharpe ratio (daily, annualised)", "{v:.3f}"),
        ("trade_count", "Trades", "{v:d}"),
        ("win_rate_pct", "Win rate", "{v:.2f}%"),
        ("profit_factor", "Profit factor", "{v:.3f}"),
        ("avg_win", "Avg win", "${v:,.2f}"),
        ("avg_loss", "Avg loss", "${v:,.2f}"),
        ("bars", "Bars processed", "{v:d}"),
    ]
    for key, label, fmt in nice:
        v = metrics[key]
        shown = "n/a" if v is None else fmt.format(v=v)
        rows.append("<tr><td>%s</td><td>%s</td></tr>" % (label, shown))

    trade_rows = []
    for k, t in enumerate(result.trades, start=1):
        cls = "pos" if t.pnl > 0 else "neg"
        trade_rows.append(
            "<tr><td>%d</td><td>%s</td><td>%.2f</td><td>%d</td><td>%s</td>"
            "<td>%.2f</td><td class='%s'>%.2f</td><td>%.2f</td>"
            "<td>%d</td><td>%s</td></tr>"
            % (k, t.entry_date, t.entry_price, t.shares, t.exit_date,
               t.exit_price, cls, t.pnl, t.return_pct, t.bars_held,
               t.exit_reason))

    import json
    cfg_text = _html.escape(json.dumps(result.config, indent=2))

    page = _PAGE_TMPL.format(
        data_file=_html.escape(data_file),
        bars=metrics["bars"],
        metrics_rows="".join(rows),
        svg=_equity_svg(result),
        initial=metrics["initial_capital"],
        final=metrics["final_equity"],
        trade_count=metrics["trade_count"],
        trade_rows="".join(trade_rows),
        config_json=cfg_text,
    )
    with open(path, "w", encoding="utf-8") as f:
        f.write(page)


def write_all_reports(result, metrics, output_dir, data_file=""):
    """Write trades.csv, equity_curve.csv and report.html to output_dir."""
    if not os.path.isdir(output_dir):
        os.makedirs(output_dir)
    write_trades_csv(result, os.path.join(output_dir, "trades.csv"))
    write_equity_csv(result, os.path.join(output_dir, "equity_curve.csv"))
    write_html_report(result, metrics,
                      os.path.join(output_dir, "report.html"), data_file)
    return {"trades_csv": os.path.join(output_dir, "trades.csv"),
            "equity_csv": os.path.join(output_dir, "equity_curve.csv"),
            "report_html": os.path.join(output_dir, "report.html")}